words = json.load(open(sys.argv[1]))
total_end = float(sys.argv[3])
chunks = []
i = 0
for line in SPEC.strip().splitlines():
    toks = []
    for tok in line.split():
        n = 1
        if '|' in tok:
            tok, n = tok.split('|')
            n = int(n)
        hl = tok.startswith('*')
        tok = tok.lstrip('*')
        start = words[i][0]
        end = words[i + n - 1][1]
        toks.append({'t': tok, 's': round(start, 3), 'e': round(end, 3), 'hl': hl})
        i += n
    chunks.append({'s': toks[0]['s'], 'w': toks})
assert i == len(words), (i, len(words))
for k, c in enumerate(chunks):
    nxt = chunks[k + 1]['s'] if k + 1 < len(chunks) else total_end
    c['e'] = round(nxt, 3)
json.dump(chunks, open(sys.argv[2], 'w'), ensure_ascii=False)
print(len(chunks), 'chunks')
